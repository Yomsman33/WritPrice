"""Regenerates Recipes.lua from AtlasLootClassic and pfQuest checkouts.
Usage: python3 gen_recipes.py <dir containing alc/ (AtlasLootClassic) and pfq/ (pfQuest)> <path to Recipes.lua>"""
import re, sys
if len(sys.argv) < 3:
    sys.exit(__doc__)
E = sys.argv[1].rstrip('/') + '/'
OUT = sys.argv[2]
prof = open(E+'alc/AtlasLootClassic/Data/Profession.lua').read()
start = prof.index('PROFESSION_DATA.CLASSIC = {'); block = prof[start:prof.index('\n}', start)]
rcp = open(E+'alc/AtlasLootClassic/Data/Recipe.lua').read()
rs = rcp.index('RECIPE_DATA.CLASSIC = {'); rblock = rcp[rs:rcp.index('\n}', rs)]
def load_names(path):
    d = {}
    for m in re.finditer(r'\[(\d+)\] = "((?:[^"\\]|\\.)*)"', open(path, encoding='utf-8', errors='replace').read()):
        d[int(m.group(1))] = m.group(2).replace("\\'", "'").replace('\\"','"')
    return d
names = load_names(E+'pfq/db/enUS/items.lua')
units = load_names(E+'pfq/db/enUS/units.lua')
data = open(E+'pfq/db/items.lua').read()
src = {}
for m in re.finditer(r'\n  \[(\d+)\] = \{\n(.*?)\n  \},', data, re.S):
    body = m.group(2); d = {}
    for key in ('V','U','O'):
        mm = re.search(r'\["%s"\] = \{(.*?)\n    \},' % key, body, re.S)
        if mm: d[key] = [int(x) for x in re.findall(r'\[(\d+)\]', mm.group(1))]
    src[int(m.group(1))] = d
# spell -> recipe item
spell2rec = {}
for m in re.finditer(r'\[(\d+)\] = \{(\d+),(\d+),(\d+)\}', rblock):
    item, sp = int(m.group(1)), int(m.group(4))
    nm = names.get(item, '')
    if nm.startswith('Deprecated'): continue
    spell2rec.setdefault(sp, item)
pat = re.compile(r'\[(\d+)\] = \{(\d+),(\d+),(\d+),\d+,\d+,\{([\d,]*)\},\{([\d,]*)\}(?:,([^}\n]*?))?\}')
rec = {}
for m in pat.finditer(block):
    sp, created, p, skill = int(m.group(1)), int(m.group(2)), int(m.group(3)), int(m.group(4))
    if p in (5,7,11,12,13): continue
    rs_ = [int(x) for x in m.group(5).split(',') if x]; cs = [int(x) for x in m.group(6).split(',') if x]
    try: n = int(m.group(7)) if m.group(7) else 1
    except: n = 1
    nm = names.get(created)
    if not nm or any(r not in names for r in rs_) or len(rs_)!=len(cs): continue
    if nm in rec and rec[nm]['s'] <= skill: continue
    rec[nm] = dict(p=p, s=skill, n=n, r=list(zip(rs_,cs)), sp=sp)
def q(s): return '"' + s.replace('\\','\\\\').replace('"','\\"') + '"'
out = ['-- SPDX-License-Identifier: GPL-2.0-only',
 '-- WritPrice: Classic recipes (crafted item -> reagents, how the recipe is learned).',
 '-- Derived from AtlasLootClassic (GPL v2; Lag, Daviesh and contributors) - Data/Profession.lua and Data/Recipe.lua -',
 '-- and pfQuest (MIT, (c) 2017-2021 Eric Mauser (Shagu)) - item and NPC names, vendors, drops.',
 '-- Generated by dev/tools/gen_recipes.py on ' + __import__('datetime').date.today().isoformat() + '; transformed into name-keyed tables. Classic-era data: WoW Forever may differ.',
 '-- t = "trainer" or "pattern"; pat = recipe item name; v = NPCs selling the recipe; d = recipe drops from creatures.',
 'local _, ns = ...',
 'ns.PROF_NAMES = { [1]="First Aid", [2]="Blacksmithing", [3]="Leatherworking", [4]="Alchemy", [6]="Cooking", [8]="Tailoring", [9]="Engineering", [10]="Enchanting", [14]="Jewelcrafting" }',
 'ns.RECIPES = {']
stats = {'trainer':0,'pattern':0}
for nm in sorted(rec):
    v = rec[nm]
    r = ', '.join(f'{q(names[i])}, {c}' for i,c in v['r'])
    extra = ''
    ri = spell2rec.get(v['sp'])
    if ri:
        stats['pattern'] += 1
        s = src.get(ri, {})
        extra = f', t = "pattern", pat = {q(names[ri])}'
        vend = [units[u] for u in s.get('V', []) if u in units][:3]
        if vend: extra += ', v = { ' + ', '.join(q(x) for x in vend) + ' }'
        if s.get('U') or s.get('O'): extra += ', d = true'
    else:
        stats['trainer'] += 1
        extra = ', t = "trainer"'
    out.append(f'  [{q(nm)}] = {{ p = {v["p"]}, s = {v["s"]}, n = {v["n"]}{extra}, r = {{ {r} }} }},')
out.append('}')
# Supplies always sold by vendors (unlimited): priced at ~4 x their sell price instead of being scanned
VENDOR_SUPPLIES = ["Refreshing Spring Water", "Ice Cold Milk", "Coarse Thread", "Fine Thread", "Bleach", "Black Dye",
  "Skin of Dwarven Stout", "Red Dye", "Green Dye", "Stormwind Seasoning Herbs", "Mild Spices", "Hot Spices", "Weak Flux",
  "Rhapsody Malt", "Empty Vial", "Leaded Vial", "Strong Flux", "Soothing Spices", "Salt", "Silken Thread", "Gray Dye",
  "Yellow Dye", "Purple Dye", "Wooden Stock", "Heavy Stock", "Simple Wood", "Shiny Red Apple", "Copper Rod", "Blue Dye",
  "Orange Dye", "Heavy Silken Thread", "Crystal Vial", "Pink Dye", "Engineer's Ink", "Blank Parchment", "Star Wood",
  "Rune Thread", "Holiday Spices", "Imbued Vial"]
first_id = {}
for i in sorted(names):
    first_id.setdefault(names[i], i)
# name -> itemID for crafted items and reagents (Auctionator prices, full-scan matching)
ids = {}
for nm, v in rec.items():
    ids.setdefault(nm, first_id.get(nm))
    for i, _ in v['r']:
        ids.setdefault(names[i], i)
out.append('-- Item IDs of crafted items and reagents (name -> itemID)')
out.append('ns.ITEM_IDS = {')
for n in sorted(k for k in ids if ids[k]):
    out.append(f'  [{q(n)}] = {ids[n]},')
out.append('}')
out.append('-- Vendor supplies (name -> itemID); buy price ~ 4 x sell price')
out.append('ns.VENDOR = {')
for n in VENDOR_SUPPLIES:
    if n in first_id:
        out.append(f'  [{q(n)}] = {first_id[n]},')
out.append('}')
open(OUT, 'w').write('\n'.join(out) + '\n')
print(len(rec), stats)
