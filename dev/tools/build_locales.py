"""Builds Locales/enUS.lua and Locales/frFR.lua from the dev/tools/strings_*.py catalogs (single source of truth)."""
import glob, importlib.util, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
rows, seen = [], {}
for path in sorted(glob.glob(os.path.join(os.path.dirname(__file__), 'strings_*.py'))):
    spec = importlib.util.spec_from_file_location(os.path.basename(path)[:-3], path)
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    for k, en, fr in mod.S:
        if k in seen:
            sys.exit(f"duplicate key {k} in {path} and {seen[k]}")
        seen[k] = path
        rows.append((k, en, fr))
def lua(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
def key(k):
    return k if k.replace('_', '').isalnum() else '[' + lua(k) + ']'
for code, idx, note in (("enUS", 1, "English (default)"), ("frFR", 2, "Français")):
    out = ["-- SPDX-License-Identifier: GPL-2.0-only", f"-- WritPrice: {note} strings. Generated by dev/tools/build_locales.py - edit the catalogs, not this file.",
           "local _, ns = ...", f"ns.LOCALES.{code} = {{"]
    for r in rows:
        out.append(f"  {key(r[0])} = {lua(r[idx])},")
    out.append("}")
    open(os.path.join(ROOT, 'Locales', code + '.lua'), 'w', encoding='utf-8').write("\n".join(out) + "\n")
print(len(rows), "keys")
